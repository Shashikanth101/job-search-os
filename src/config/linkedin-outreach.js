function searchUrl(company, linkedinCompanyId, keywords) {
  if (linkedinCompanyId !== null) {
    return `https://www.linkedin.com/search/results/people/?currentCompany=${encodeURIComponent(JSON.stringify([String(linkedinCompanyId)]))}&keywords=${encodeURIComponent(keywords)}`;
  }
  return `https://www.linkedin.com/search/results/people/?keywords=${encodeURIComponent(`${company} ${keywords}`)}`;
}

export default companies.map(({ company, linkedinCompanyId }) => ({
  company,
  recruiterUrl: searchUrl(company, linkedinCompanyId, 'recruiter'),
  hiringManagerUrl: searchUrl(company, linkedinCompanyId, 'engineering manager'),
}));
